using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using UnityEditor;
using UnityEngine;

namespace ModuleTools.Audio
{
	public static class AudioKeysGenerator
	{
		static readonly Regex CamelBoundary = new Regex(@"(?<=[a-z0-9])(?=[A-Z])");

		public static string ToConstantName(string key)
		{
			if (string.IsNullOrWhiteSpace(key)) return "";

			string spaced = CamelBoundary.Replace(key.Trim(), "_");
			var sb = new StringBuilder(spaced.Length);

			foreach (char c in spaced)
			{
				sb.Append(char.IsLetterOrDigit(c) ? char.ToUpperInvariant(c) : '_');
			}

			string collapsed = Regex.Replace(sb.ToString(), "_+", "_").Trim('_');

			if (collapsed.Length == 0) return "";

			return char.IsDigit(collapsed[0]) ? "_" + collapsed : collapsed;
		}

		public static List<AudioCatalogSO> LocateAll()
		{
			return AssetDatabase.FindAssets("t:AudioCatalogSO")
				.Select(AssetDatabase.GUIDToAssetPath)
				.Select(AssetDatabase.LoadAssetAtPath<AudioCatalogSO>)
				.Where(c => c != null)
				.OrderBy(c => c.name)
				.ToList();
		}

		public static List<string> Validate(IList<AudioCatalogSO> catalogs)
		{
			var errors = new List<string>();

			if (catalogs == null || catalogs.Count == 0)
			{
				errors.Add("Không tìm thấy AudioCatalogSO nào trong project.");
				return errors;
			}

			var seenKeys = new Dictionary<string, string>();
			var seenNames = new Dictionary<string, string>();
			int total = 0;

			foreach (AudioCatalogSO catalog in catalogs)
			{
				for (int i = 0; i < catalog.audioConfigs.Count; i++)
				{
					AudioEntry entry = catalog.audioConfigs[i];
					string key = entry?.key ?? "";
					string label = $"{catalog.name} dòng {i + 1}";
					total++;

					if (string.IsNullOrWhiteSpace(key))
					{
						errors.Add($"{label}: chưa đặt key.");
						continue;
					}

					if (seenKeys.TryGetValue(key.ToLower(), out string owner))
					{
						errors.Add($"{label}: key '{key}' trùng với {owner}.");
						continue;
					}

					seenKeys[key.ToLower()] = label;

					string name = ToConstantName(key);

					if (name.Length == 0)
					{
						errors.Add($"{label}: key '{key}' không sinh được tên hằng hợp lệ.");
						continue;
					}

					if (seenNames.TryGetValue(name, out string clash))
					{
						errors.Add($"{label}: key '{key}' sinh ra '{name}', trùng với {clash}.");
						continue;
					}

					seenNames[name] = $"{label} (key '{key}')";
				}
			}

			if (total == 0) errors.Add("Catalog rỗng — fill từ folder trước khi generate.");

			return errors;
		}

		public static bool Generate(IList<AudioCatalogSO> catalogs, string path)
		{
			List<string> errors = Validate(catalogs);

			if (errors.Count > 0)
			{
				Debug.LogError("[Audio] Không generate được:\n- " + string.Join("\n- ", errors));
				return false;
			}

			var entries = new List<(string Name, string Key)>();

			foreach (AudioCatalogSO catalog in catalogs)
			{
				foreach (AudioEntry entry in catalog.audioConfigs)
				{
					entries.Add((ToConstantName(entry.key), entry.key));
				}
			}

			entries.Sort((a, b) => string.CompareOrdinal(a.Name, b.Name));

			var sb = new StringBuilder();
			sb.AppendLine("// <auto-generated>");
			sb.AppendLine("// Sinh tu AudioCatalogSO. Khong sua tay.");
			sb.AppendLine("// Sua bang trong Tools/DevTool -> Audio roi bam Generate Keys.");
			sb.AppendLine("// </auto-generated>");
			sb.AppendLine();
			sb.AppendLine("public static class AudioKeys");
			sb.AppendLine("{");

			foreach ((string name, string key) in entries)
			{
				sb.AppendLine($"    public const string {name} = \"{key}\";");
			}

			sb.AppendLine();
			sb.AppendLine("    public static readonly string[] All =");
			sb.AppendLine("    {");

			foreach ((string name, string _) in entries)
			{
				sb.AppendLine($"        {name},");
			}

			sb.AppendLine("    };");
			sb.AppendLine("}");

			string full = Path.Combine(Directory.GetCurrentDirectory(), path);
			Directory.CreateDirectory(Path.GetDirectoryName(full));
			File.WriteAllText(full, sb.ToString(), new UTF8Encoding(false));

			AssetDatabase.ImportAsset(path);
			AssetDatabase.Refresh();

			Debug.Log($"<color=cyan>[Audio]</color> Đã generate {path} với {entries.Count} key từ {catalogs.Count} catalog.");
			return true;
		}
	}
}
